# 1. DECLARACIÓN DE VARIABLES
edad: int  #almacena la edad como número entero
ingresos: float  #almacena los ingresos, puede ser decimal
impuesto: float  #almacena el impuesto, puede ser decimal

# 2. ENTRADA DE DATOS
edad = int(input("Ingrese su edad: ")) #ingresar la edad
ingresos = float(input("Ingrese sus ingresos mensuales: ")) #ingresar monto

# 3. DESARROLLO
# Se evaluan ambas condiciones: mayor de 18 años Y ingresos >= 3000
if edad > 18 and ingresos >= 3000:
    impuesto = ingresos * 0.05

# 4. SALIDA DE RESULTADOS
#Se muestra si la persona debe tributar y el monto que debe pagar.
#Si no cumple las condiciones, se indica que no tiene que tributar.
    print("Usted SI tiene que tributar.")
    print(f"El monto a tributar es: S/ {impuesto:.2f}")
else:
    print("Usted NO tiene que tributar.")
    print("El monto a tributar es: S/ 0.00")