# 1. DECLARACIÓN DE VARIABLES
numero1: float #almacena un numero, puede ser decimal
numero2: float #almacena un numero, puede ser decimal
numero3: float #almacena un numero, puede ser decimal
mayor: float #almacena al numero mayor, puede ser decimal
menor: float #almacena al numero menor, puede ser decimal

# 2. ENTRADA
numero1 = float(input("Ingrese el primer número: "))
numero2 = float(input("Ingrese el segundo número: "))
numero3 = float(input("Ingrese el tercer número: "))

# 3. DESARROLLO
if numero1 >= numero2 and numero1 >= numero3:
    mayor = numero1
else:
    if numero2 >= numero1 and numero2 >= numero3:
        mayor = numero2
    else:
        mayor = numero3

if numero1 <= numero2 and numero1 <= numero3:
    menor = numero1
else:
    if numero2 <= numero1 and numero2 <= numero3:
        menor = numero2
    else:
        menor = numero3

# 4. SALIDA
print("El número mayor es:", mayor)
print("El número menor es:", menor)