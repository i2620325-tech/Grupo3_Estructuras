"""
ESTRUCTURAS CONDICIONALES - EJERCICIO 5

DESCRIPCIÓN:
Calcular el total que una persona debe pagar en una llantera, si el
precio de cada llanta es de S/150 si se compran menos de 5 llantas y
de S/120 si se compran 5 o más
"""

# 1. DECLARACIÓN DE VARIABLES
cantidad: int
precio: float
total: float

# 2. ENTRADA
cantidad = int(input("Ingrese la cantidad de llantas que desea comprar: "))

# 3. DESARROLLO
if cantidad < 5:
    precio = 150
else:
    precio = 120

total = cantidad * precio

# 4. SALIDA
print("Cantidad de llantas:", cantidad)
print(f"Precio por llanta: S/ {precio:.2f}")
print(f"El total a pagar es: S/ {total:.2f}")