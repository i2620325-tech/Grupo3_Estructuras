"""
ESTRUCTURAS CONDICIONALES - EJERCICIO 8

DESCRIPCIÓN:
Calcular el pago de una llamada, el cobro es por el tiempo que ésta
dura, de tal forma que los primeros cinco minutos cuestan S/ 1.00 c/u,
los siguientes tres, S/0.80 c/u, los siguientes dos minutos, S/0.70 c/u,
3
y a partir del décimo minuto, S/0.50 c/u. Además, se carga un
impuesto de 3 % cuando es domingo, y 5% si es domingo de turno
nocturno. Realice un algoritmo para determinar cuánto debe pagar
por cada concepto una persona que realiza una llamada.
"""

# 1. DECLARACIÓN DE VARIABLES
minutos: int
dia: str
turno: str
pago: float
impuesto: float
total: float

# 2. ENTRADA
minutos = int(input("Ingrese los minutos de la llamada: "))
dia = input("¿Es domingo? (si/no): ").lower()
turno = input("¿Es turno nocturno? (si/no): ").lower()

# 3. DESARROLLO
if minutos <= 5:
    pago = minutos * 1.00
elif minutos <= 8:
    pago = 5 + (minutos - 5) * 0.80
elif minutos <= 10:
    pago = 7.40 + (minutos - 8) * 0.70
else:
    pago = 8.80 + (minutos - 10) * 0.50

if dia == "si" and turno == "si":
    impuesto = pago * 0.05
elif dia == "si":
    impuesto = pago * 0.03
else:
    impuesto = 0

total = pago + impuesto

# 4. SALIDA
print(f"Costo de llamada: S/ {pago:.2f}")
print(f"Impuesto: S/ {impuesto:.2f}")
print(f"Total a pagar: S/ {total:.2f}")